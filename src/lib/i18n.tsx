interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
});

export function syncGoogleTranslate(lang?: SupportedLanguage) {
  try {
    const hostname = window.location.hostname;
    const domains = [hostname, '.' + hostname, ''];
    const paths = ['/', window.location.pathname];
    if (!lang || lang === 'en') {
      domains.forEach((d) => {
        paths.forEach((p) => {
          document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=${p};${d ? ` domain=${d};` : ''}`;
        });
      });
      sessionStorage.removeItem('googtrans');
      localStorage.removeItem('googtrans');
    } else {
      domains.forEach((d) => {
        paths.forEach((p) => {
          document.cookie = `googtrans=/en/${lang}; path=${p};${d ? ` domain=${d};` : ''}`;
        });
      });
    }
  } catch {
    // Cookie cleanup
  }
}

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<SupportedLanguage>(() => {
    try {
      const saved = localStorage.getItem('foodlink_language') as SupportedLanguage;
      if (saved && TRANSLATIONS[saved]) return saved;
      return 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (lang: SupportedLanguage) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('foodlink_language', lang);
      document.documentElement.lang = lang;
      syncGoogleTranslate(lang);
      window.dispatchEvent(new CustomEvent('foodlink_language_changed', { detail: { lang } }));
    } catch {
      // Storage exception
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
    syncGoogleTranslate(language);
  }, [language]);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) return langDict[key];
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) return TRANSLATIONS.en[key];
    return fallback !== undefined ? fallback : key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
